"""PP1 demo: the real Phase 1-3 pipeline on the labelled synthetic prototype.

No database. The prototype model and C2 emulator (``ml.explainability.demo``)
stand in for C2 until its trained artifact on the shared feature contract
exists. Every response carries the synthetic data-source label.

Flow per flag (unchanged C4 code): AnalysisService.build_context ->
ReliabilityEvaluator (SHAP, LIME, Agreement, Stability, Faithfulness, ECS).
Results are computed once per flag and cached.
"""

import asyncio
import logging
import tempfile
from pathlib import Path
from uuid import UUID

from backend.app.explainability.api_schemas import (
    AnalysisResponse,
    DataSource,
    DemoFlagList,
    DemoFlagSummary,
    FeatureInfo,
    FeatureVectorInfo,
    ModelInfo,
    TimelineWindow,
)
from backend.app.explainability.errors import FlagNotFoundError
from backend.app.explainability.evaluation.reliability import ReliabilityEvaluator
from backend.app.explainability.explanations.background import load_background
from backend.app.explainability.feature_registry import load_feature_registry
from backend.app.explainability.model.artifact_loader import ArtifactLoader
from backend.app.explainability.schemas import AnalysisContext
from backend.app.explainability.service import AnalysisService
from ml.explainability.demo.prototype import (
    REGISTRY_PATH,
    InMemoryC2Reader,
    artifact_dict,
    background_reference,
    build_prototype_model,
    emulate_c2,
    load_scenarios,
    write_artifact,
    write_background,
)

logger = logging.getLogger(__name__)

DATA_SOURCE = DataSource(
    kind="synthetic_prototype",
    label="Prototype data source: synthetic behavioural dataset / integration model",
    note=(
        "Generated by a synthetic prototype standing in for the C2 classifier. "
        "Demonstrates the explanation pipeline; it is not evidence about real candidates."
    ),
)

PLANNED = {
    "counterfactuals": "Phase 4 (DiCE) - next",
    "behavioural_realism": "Phases 5-6 (CRS) - designed, not yet implemented",
}

_TITLES = {
    "external_ai_segment": "External-AI segment",
    "ide_ai_segment": "IDE-AI segment",
}


class DemoExplainability:
    def __init__(self) -> None:
        workdir = Path(tempfile.mkdtemp(prefix="c4-demo-"))
        model = build_prototype_model()
        self._records = emulate_c2(model, load_scenarios())
        write_artifact(workdir, artifact_dict(model))
        write_background(workdir)
        self._workdir = workdir
        self._reader = InMemoryC2Reader(self._records)
        self._service = AnalysisService(
            self._reader,
            ArtifactLoader(workdir),
            load_feature_registry(REGISTRY_PATH),
            dev_background_ref=background_reference(),
        )
        self._evaluator = ReliabilityEvaluator()
        self._names = {fid: name for name, fid in self._records.flag_ids_by_name.items()}
        self._cache: dict[UUID, AnalysisResponse] = {}
        self._lock = asyncio.Lock()
        logger.info("C4 demo ready with %d prototype flags", len(self._names))

    def flags(self) -> DemoFlagList:
        summaries = []
        for flag_id, name in self._names.items():
            flag = self._records.flags[flag_id]
            summaries.append(
                DemoFlagSummary(
                    flag_id=flag_id,
                    title=_TITLES.get(name, name),
                    task_id=flag["task_id"],
                    category=flag["category"],
                    confidence=flag["confidence"],
                    window_count=flag["window_count"],
                    model_version=flag["model_version"],
                )
            )
        return DemoFlagList(data_source=DATA_SOURCE, flags=tuple(summaries))

    async def analysis(self, flag_id: UUID) -> AnalysisResponse:
        if flag_id not in self._names:
            raise FlagNotFoundError(f"no demo flag {flag_id}")
        async with self._lock:
            cached = self._cache.get(flag_id)
            if cached is None:
                cached = await self._compute(flag_id)
                self._cache[flag_id] = cached
        return cached

    async def _compute(self, flag_id: UUID) -> AnalysisResponse:
        context = await self._service.build_context(flag_id)
        adapter = self._service.adapter_for(context.model_version)
        assert context.background_ref is not None  # the demo always configures one
        background = load_background(context.background_ref, context.artifact,
                                     base_dir=self._workdir)
        report = await asyncio.to_thread(self._evaluator.evaluate, context, adapter, background)
        timeline = await self._timeline(context)
        vector = context.feature_vector
        return AnalysisResponse(
            data_source=DATA_SOURCE,
            flag=context.flag,
            representative_prediction=context.representative_prediction,
            feature_vector=FeatureVectorInfo(
                feature_vector_id=vector.feature_vector_id,
                session_id=vector.session_id,
                task_id=vector.task_id,
                window_start=vector.window_start,
                window_end=vector.window_end,
                run_id=vector.run_id,
                schema_version=vector.schema_version,
            ),
            model=ModelInfo(
                model_version=context.model_version,
                model_family=context.model_family,
                feature_schema_version=context.feature_schema_version,
                classification_threshold=context.artifact.classification_threshold,
                class_names=context.class_names,
                target_class=context.target_class,
                target_class_index=context.target_class_index,
            ),
            features=tuple(
                FeatureInfo(
                    name=name,
                    value=context.model_input[name],
                    label=context.feature_metadata.get(name, {}).get("label"),
                    unit=context.feature_metadata.get(name, {}).get("unit"),
                    display_as=context.feature_metadata.get(name, {}).get("display_as"),
                    description=context.feature_metadata.get(name, {}).get("description"),
                )
                for name in context.feature_names
            ),
            timeline=timeline,
            shap=report.shap,
            lime=report.lime,
            agreement=report.agreement,
            stability=report.stability.model_dump(mode="json", exclude={"runs"}),
            faithfulness=report.faithfulness,
            ecs=report.ecs,
            ecs_sensitivity=report.ecs_sensitivity,
            planned=PLANNED,
        )

    async def _timeline(self, context: AnalysisContext) -> tuple[TimelineWindow, ...]:
        members = set(context.contributing_prediction_ids)
        representative = context.representative_prediction.prediction_id
        windows = []
        for prediction in await self._reader.get_task_window_predictions(
            context.flag.task_id, context.model_version
        ):
            vector = await self._reader.get_feature_vector(prediction.feature_vector_id)
            windows.append(
                TimelineWindow(
                    prediction_id=prediction.prediction_id,
                    window_start=vector.window_start,
                    window_end=vector.window_end,
                    predicted_category=prediction.predicted_category,
                    confidence=prediction.confidence,
                    ai_positive=prediction.ai_positive,
                    in_segment=prediction.prediction_id in members,
                    is_representative=prediction.prediction_id == representative,
                )
            )
        return tuple(windows)
